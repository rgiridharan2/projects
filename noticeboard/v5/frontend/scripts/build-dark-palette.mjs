// Generates src/theme-dark.css: the dark theme as a remap of Tailwind's own colour variables.
//
//   node scripts/build-dark-palette.mjs
//
// In Tailwind v4 every colour utility reads a CSS variable (bg-slate-50 -> var(--color-slate-50)).
// So instead of adding dark:bg-... to every element, the .dark class points each light shade at
// its dark counterpart, and every component (including future ones) switches theme at once.
import { readFileSync, writeFileSync } from "node:fs";

const theme = readFileSync(new URL("../node_modules/tailwindcss/theme.css", import.meta.url), "utf8");
const value = (name, shade) => {
  const match = theme.match(new RegExp(`--color-${name}-${shade}:\\s*([^;]+);`));
  if (!match) throw new Error(`No --color-${name}-${shade} in Tailwind's theme`);
  return match[1].trim();
};

// Neutrals: page/card backgrounds go dark, text goes light. Muted (400) and secondary (500) text
// both use slate-400 in dark mode: anything darker drops below 4.5:1 contrast on navy.
const NEUTRAL = { 50: 950, 100: 800, 200: 800, 300: 700, 400: 400, 500: 400, 600: 300, 700: 200, 800: 100, 900: 50, 950: 50 };
// Accent colours: pale tints become deep tints, dark text on tints becomes light text. 400-600 stay
// put, because they're the solid fills behind white button text and icons.
const ACCENT = { 50: 950, 100: 900, 200: 800, 300: 700, 700: 300, 800: 200, 900: 100, 950: 50 };

const NEUTRALS = ["slate"];
const ACCENTS = ["red", "amber", "emerald", "sky", "violet", "indigo", "teal", "fuchsia", "lime"];

const lines = [];
for (const name of NEUTRALS) {
  for (const [from, to] of Object.entries(NEUTRAL)) lines.push(`  --color-${name}-${from}: ${value(name, to)};`);
}
for (const name of ACCENTS) {
  for (const [from, to] of Object.entries(ACCENT)) lines.push(`  --color-${name}-${from}: ${value(name, to)};`);
}

writeFileSync(
  new URL("../src/theme-dark.css", import.meta.url),
  `/* GENERATED by scripts/build-dark-palette.mjs from Tailwind's palette. Don't edit by hand. */
/* Under .dark, each light shade points at its dark counterpart (see the script for the mapping). */
.dark {
  color-scheme: dark; /* native scrollbars, date pickers and selects go dark too */
  --color-surface: ${value("slate", 900)}; /* cards and panels: navy */
${lines.join("\n")}
}
`,
);
console.log(`Wrote src/theme-dark.css (${lines.length} colour variables)`);
